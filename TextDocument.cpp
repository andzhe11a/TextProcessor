#include "TextDocument.h"
#include "LineTypes.h"
#include <fstream>
#include <iostream>

// Конструкторът запазва пътя до файла и веднага извиква load(),
// за да зареди съдържанието му в паметта при създаване на обекта.
TextDocument::TextDocument(const std::string& path) {
    this->filename = path;
    this->unsavedChanges = false;
    load();
}

TextDocument::~TextDocument() {
    clear();
}

// Този метод е ключов за избягване на изтичане на памет (memory leaks).
// Той обхожда вектора с указатели и изрично изтрива всеки Line обект,
// след което изчиства и самия вектор, премахвайки указателите.
void TextDocument::clear() {
    for (size_t i = 0; i < lines.size(); ++i) {
        delete lines[i];
    }
    lines.clear();
}

bool TextDocument::load() {
    // 1. ПОДГОТОВКА: Първо извикваме clear(), за да изтрием всяко старо съдържание
    // и да избегнем изтичане на памет (memory leak) при презареждане на файл.
    clear();

    // 2. ОТВАРЯНЕ НА ФАЙЛА: Опитваме се да отворим файла за четене.
    std::ifstream inFile(this->filename);

    // Проверяваме дали отварянето е било успешно.
    if (!inFile) {
        // Ако файлът не съществува, приемаме, че е нов/празен документ.
        // Няма незапазени промени и функцията приключва успешно.
        this->unsavedChanges = false;
        return true;
    }

    // 3. ЧЕТЕНЕ РЕД ПО РЕД: Основен цикъл, който чете файла докрай.
    std::string lineFromFile; // Временна променлива за текста от всеки ред.
    // Цикълът продължава, докато std::getline успява да прочете нов ред от файла.
    while (std::getline(inFile, lineFromFile)) {
        // За всеки прочетен текстов ред, извикваме фабричната функция createLine().
        // Тя анализира текста и връща указател към обект от правилния тип (Numbered, Quoted и т.н.).
        // След това добавяме този указател в края на нашия вектор от редове.
        lines.push_back(createLine(lineFromFile));
    }

    // 4. ФИНАЛИЗИРАНЕ: След като целият файл е прочетен...
    // ...затваряме файла, за да освободим системния ресурс.
    inFile.close();
    // ...нулираме флага за промени, защото съдържанието в паметта вече отговаря на това на диска.
    this->unsavedChanges = false;
    // ...и връщаме 'true', за да сигнализираме, че операцията е успешна.
    return true;
}

bool TextDocument::save() {
    // 1. ОТВАРЯНЕ НА ФАЙЛА: Опитваме се да отворим файла за писане.
    // 'ofstream' създава нов файл или презаписва съществуващ.
    std::ofstream outFile(this->filename);

    // Проверяваме дали отварянето е било успешно.
    if (!outFile) {
        std::cerr << "Error: Could not open file for writing: " << this->filename << std::endl;
        return false;
    }

    // 2. ЗАПИС НА СЪДЪРЖАНИЕТО: Обхождаме всички редове в паметта.
    for (size_t i = 0; i < lines.size(); ++i) {
        // За всеки указател към Line обект ('lines[i]'), извикваме неговия метод getText().
        // Резултатът (текстът на реда) се записва във файла, последван от символ за нов ред ('\n').
        outFile << lines[i]->getText() << '\n';
    }

    // 3. ФИНАЛИЗИРАНЕ: След като всички редове са записани...
    // ...затваряме файла, за да освободим ресурса.
    outFile.close();
    // ...нулираме флага за промени, защото съдържанието в паметта вече отговаря на това на диска.
    this->unsavedChanges = false;
    // ...и връщаме 'true', за да сигнализираме, че операцията е успешна.
    return true;
}

bool TextDocument::saveAs(const std::string& newPath) {
    // 1. АКТУАЛИЗИРАНЕ НА ПЪТЯ: Първо, сменяме пътя на файла, съхраняван
    // в член-променливата 'filename', с новия път, подаден на функцията.
    filename = newPath;

    // 2. ПРЕИЗПОЛЗВАНЕ НА SAVE(): След като пътят е вече новият, просто извикваме
    // стандартната функция save(). Тя ще свърши цялата работа по отваряне,
    // писане и затваряне, но този път ще използва новото име на файла.
    return save();
}

std::string TextDocument::getFilename() const {
    return this->filename;
}

bool TextDocument::hasUnsavedChanges() const {
    return this->unsavedChanges;
}

size_t TextDocument::getLineCount() const {
    return this->lines.size();
}

size_t TextDocument::getCharacterCount() const {
    size_t count = 0;
    for (size_t i = 0; i < lines.size(); ++i) {
        count += lines[i]->getText().length();
    }
    return count;
}

// Гетъри с разделени отговорности:
// - getLineObject(): За "вътрешната" логика. Връща целия обект (BaseLine*) за команди
//   като Sort, които се нуждаят от достъп до полиморфното му поведение (напр. isMovable).
// - getLineText(): За "външни" операции. Връща само текста (std::string) за удобство
//   на функции извън класа, които се нуждаят единствено от данните.
BaseLine* TextDocument::getLineObject(size_t index) const {
    // Ако индексът е извън границите на вектора...
    if (index >= lines.size()) {
        // ...връщаме nullptr (нулев указател), за да покажем, че такъв ред не съществува.
        return nullptr;
    }
    // В противен случай връщаме указателя към Line обекта на този индекс.
    return lines[index];
}

std::string TextDocument::getLineText(size_t index) const {
    // Ако индексът е извън границите на вектора...
    if (index >= lines.size()) {
        // ...връщаме празен низ.
        return "";
    }
    // В противен случай взимаме обекта и извикваме неговия getText() метод.
    return lines[index]->getText();
}

void TextDocument::setLineText(size_t index, const std::string& newText) {
    // Проверка за валидност на индекса.
    if (index >= lines.size()) {
        return; // Ако е невалиден, не правим нищо.
    }
    // 1. ИЗТРИВАНЕ: Първо освобождаваме паметта, заета от СТАРИЯ Line обект,
    // който се намира на този индекс. Това предотвратява memory leak.
    delete lines[index];

    // 2. ЗАМЯНА: На същото място във вектора записваме указател към чисто НОВ
    // Line обект, създаден от фабричната функция с новия текст.
    lines[index] = createLine(newText);

    // 3. МАРКИРАНЕ: Маркираме документа като "променен", за да може програмата
    // да попита потребителя дали да запази промените при затваряне.
    this->unsavedChanges = true;
}

// --- Методи за добавяне и премахване на редове ---
// Това са основните функции за промяна на структурата на документа.


// Вмъква нов ред на определена позиция.
// Създава нов Line обект и го вмъква във вектора, като измества
// всички следващи редове с една позиция надолу.
void TextDocument::insertLine(size_t index, const std::string& newText) {
    // 1. ПРОВЕРКА: Проверяваме дали индексът е валиден. За вмъкване,
    // индексът може да бъде от 0 до 'lines.size()' (за вмъкване най-отзад).
    if (index > lines.size()) {
        return; // Ако е невалиден, не правим нищо.
    }

    // 2. СЪЗДАВАНЕ: Използваме фабричната функция, за да създадем нов Line
    // обект в паметта от подадения текст.
    BaseLine* newLine = createLine(newText);

    // 3. ВМЪКВАНЕ: Използваме вградения метод 'insert' на вектора, за да
    // добавим указателя към новосъздадения обект на желаната позиция.
    lines.insert(lines.begin() + index, newLine);

    // 4. МАРКИРАНЕ: Маркираме документа като "променен".
    this->unsavedChanges = true;
}

// Премахва ред от определена позиция.
// Тази операция изисква много внимателно управление на паметта,
// за да се избегнат грешки. Следва се стриктна последователност "запази, премахни, изтрий".
void TextDocument::removeLine(size_t index) {
    // 1. ПРОВЕРКА: Проверяваме дали индексът е валиден. За премахване,
    // индексът трябва да е в границите от 0 до 'lines.size() - 1'.
    if (index >= lines.size()) {
        return;
    }

    // 2. ЗАПАЗИ: Преди да променяме вектора, запазваме указателя към
    // обекта, който ще трием, във временна променлива.
    BaseLine* lineToDelete = lines[index];

    // 3. ПРЕМАХНИ: Премахваме указателя от вектора. Сега векторът вече
    // не "знае" за този обект, но той все още съществува в паметта.
    lines.erase(lines.begin() + index);

    // 4. ИЗТРИЙ: Използваме запазения указател, за да изтрием самия
    // обект от паметта и да я освободим. Това предотвратява memory leak.
    delete lineToDelete;

    // 5. МАРКИРАНЕ: Маркираме документа като "променен".
    this->unsavedChanges = true;
}