#pragma once
#include <string>

class Command;
class TextDocument;

// // Клас, чиято единствена отговорност е да преобразува (парсира)
// // потребителски вход (низ) в конкретен обект-команда.
// // Това е имплементация на "Factory" патерна за създаване на команди.
class CommandParser {
public:
    // // Основният метод на класа. Приема текстов вход и указател към активния
    // // документ и връща указател към новосъздаден обект-команда.
    // // Ако входът е невалиден, връща nullptr.
    Command* parse(const std::string& input, TextDocument* doc);
};