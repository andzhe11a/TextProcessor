#include "LineTypes.h"

StandardLine::StandardLine(const std::string& lineText) : BaseLine(lineText) {}

NumberedLine::NumberedLine(const std::string& lineText) : BaseLine(lineText) {}
// Предефинира поведението: номерираните редове не са подвижни.
bool NumberedLine::isMovable() const {
    return false;
}

QuotedLine::QuotedLine(const std::string& lineText) : BaseLine(lineText) {}
// Предефинира поведението: цитираните редове не могат да се трансформират.
bool QuotedLine::isTransformable() const {
    return false;
}

NumericLine::NumericLine(const std::string& lineText) : BaseLine(lineText) {}
// Предефинира поведението: този тип ред се идентифицира като числов.
bool NumericLine::isNumeric() const {
    return true;
}

// Проверява дали подаденият низ се състои само от цифри.
bool isStringAllDigits(const std::string& str) {
    if (str.empty()) {
        return false;
    }
    for (int i = 0; i < str.length(); ++i) {
        char c = str[i];
        if (c < '0' || c > '9') {
            return false;
        }
    }
    return true;
}

// Премахва водещи и завършващи празни символи (интервали, табулации) от низ.
// 'const std::string&' се използва за ефективност - за да се избегне копирането на целия низ.
std::string trim(const std::string& str) {
    int start = 0;
    // Докато не сме стигнали края на низа И текущият символ е интервал или табулация...
    while (start < str.length() && (str[start] == ' ' || str[start] == '\t')) {
        // ...преминаваме към следващия символ.
        start++;
    }
    // Когато този цикъл приключи, 'start' ще бъде индексът на първия символ,
    // който НЕ е празно място. Например за "  abc", start ще стане 2.

    // Започваме от последния символ на низа.
    int end = str.length() - 1;
    // Докато не сме стигнали началото на низа И текущият символ е интервал или табулация...
    while (end >= 0 && (str[end] == ' ' || str[end] == '\t')) {
        // ...преминаваме към предишния символ (движим се назад).
        end--;
    }
    // Когато този цикъл приключи, 'end' ще бъде индексът на последния символ,
    // който НЕ е празно място. Например за "abc  ", end ще стане 2.

    // Специален случай: Ако целият низ е бил от празни символи, тогава 'start' ще е станал
    // по-голям от 'end'. В този случай трябва да върнем празен низ.
    if (start > end) {
        return "";
    }

    // Използваме метода 'substr', за да изрежем част от оригиналния низ.
    // Първият параметър е от кой индекс да започне изрязването ('start').
    // Вторият параметър е КОЛКО символа да се изрежат (дължината).
    // Дължината се изчислява като (краен_индекс - начален_индекс + 1).
    // Например, ако start=3 и end=7, дължината е 7-3+1 = 5 символа.
    return str.substr(start, end - start + 1);
}

// Тази "фабрична функция" е отговорна за създаването на правилния тип Line обект.
// Тя анализира съдържанието на подадения низ и решава кой от наследяващите класове да създаде.
// Редът на проверките е важен, за да се обработят правилно по-специфичните случаи.
BaseLine* createLine(const std::string& rawLine) {
    // Първо, създаваме копие на низа без водещи/завършващи празни символи.
    // Това копие се използва САМО за по-лесен и надежден анализ в проверките по-долу.
    std::string trimmedLine = trim(rawLine);

    // ВАЖНО: Всички обекти по-долу се създават с оригиналния низ 'rawLine',
    // а не с 'trimmedLine'. Това е така, за да се запази оригиналното
    // форматиране на потребителя, включително всички интервали.


    // 1. Проверка за цитиран ред (има най-висок приоритет).
    // Проверяваме дали изчистеният ред има поне 2 символа и дали започва и завършва с кавички.
    if (trimmedLine.length() >= 2 && trimmedLine.front() == '"' && trimmedLine.back() == '"') {
        // Ако е така, създаваме обект от тип QuotedLine.
        return new QuotedLine(rawLine);
    }


    // 2. Проверка за номериран ред.
    // Търсим позицията на първата точка в изчистения низ.
    size_t dotPos = trimmedLine.find('.');
    // Ако е намерена точка (позицията не е 'npos') И тя не е първият символ (позицията е > 0)...
    if (dotPos != std::string::npos && dotPos > 0) {
        // ...извличаме частта от низа преди точката.
        std::string numPart = trimmedLine.substr(0, dotPos);
        // ...и проверяваме дали тази част е съставена само от цифри.
        if (isStringAllDigits(numPart)) {
            // Ако е така, създаваме обект от тип NumberedLine.
            return new NumberedLine(rawLine);
        }
    }


    // 3. Проверка за изцяло числов ред.
    // Тази проверка е след номерирания ред, за да не класифицира грешно "123." като число.
    if (isStringAllDigits(trimmedLine)) {
        // Ако целият изчистен ред е число, създаваме обект от тип NumericLine.
        return new NumericLine(rawLine);
    }


    // 4. Резервен вариант (по подразбиране).
    // Ако нито една от горните по-специфични проверки не е успешна,
    // приемаме, че редът е стандартен и създаваме обект от тип StandardLine.
    return new StandardLine(rawLine);
}