#pragma once

class TextDocument;

// Абстрактен базов клас (интерфейс) за всички команди в програмата.
// Този клас е основата на "Command" дизайн патерна. Той дефинира
// "договора", който всяка конкретна команда (напр. SortCommand, EditCommand)
// трябва да спазва. Тъй като има чисти виртуални функции, не могат да се
// създават директно обекти от този клас - той служи само като шаблон.
class Command {
public:
    virtual ~Command() = default;

    // Метод, който изпълнява логиката на самата команда.
    virtual void execute() = 0;

    // Метод, който отменя действието, извършено от execute().
    // Това е основата за 'undo' функционалността.
    virtual void undo() = 0;

    virtual void setDocument(TextDocument* doc) {}
};