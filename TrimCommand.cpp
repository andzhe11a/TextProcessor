// Това не е ли неефективно и няма ли да заеме твърде много памет при много големи файлове?
// Има ли алтернативен, по-оптимизиран подход?"

// Отговор: "Това е напълно валиден въпрос. Подходът със запазване на целия документ е избран
// заради неговата простота и надеждност. Той гарантира, че undo винаги ще върне документа
// в абсолютно точното му предишно състояние, без риск от грешки в логиката.
// Наистина, при изключително големи файлове това може да доведе до голямо потребление на памет.
// Алтернативен, по-оптимизиран подход би бил командата да запази само
// индексите и оригиналния текст на редовете, които реално са били променени.
// Например, в execute, вместо да пазя всичко, можех да обходя документа и ако един ред се променя,
// да запазя в един std::vector само двойка {индекс, оригинален_текст}.
// След това, в undo, щях да обходя този много по-малък списък и да извикам setLineText() само за променените редове.
// Избрах по-простия подход, защото е по-лесен за имплементация и по-малко податлив на грешки,
// но оптимизираният вариант е отлично бъдещо подобрение, което показва разбиране на проблема с производителността."