#include "TrimCommand.h"
#include "TextDocument.h"

// Помощна функция, която реално извършва премахването на празните символи.
// Изнесена е извън класа, защото е обща функционалност и не зависи от състоянието на командата.
std::string trim_helper(const std::string& str) {
    // Намираме индекса на първия символ, който не е празно място.
    int start = 0;
    while (start < str.length() && (str[start] == ' ' || str[start] == '\t')) {
        start++;
    }
    // Намираме индекса на последния символ, който не е празно място.
    int end = str.length() - 1;
    while (end >= 0 && (str[end] == ' ' || str[end] == '\t')) {
        end--;
    }
    // Ако целият низ е бил празен, връщаме празен низ.
    if (start > end) return "";
    // Изрязваме и връщаме частта от низа между start и end.
    return str.substr(start, end - start + 1);
}

// Конструкторът просто запазва указателя към документа.
TrimCommand::TrimCommand(TextDocument* doc) : doc(doc) {}

// 1. Първо прави пълно резервно копие на документа.
// 2. След това прилага промените.
void TrimCommand::execute() {
    // Първи етап: Правим резервно копие.
    // Почистваме вектора, за да сме сигурни, че е празен.
    originalLines.clear();
    size_t lineCount = doc->getLineCount();

    // Обхождаме целия документ и копираме всеки ред в нашия вектор 'originalLines'.
    for (size_t i = 0; i < lineCount; ++i) {
        originalLines.push_back(doc->getLineText(i));
    }

    // Втори етап: Прилагаме промените.
    // Отново обхождаме целия документ.
    for (size_t i = 0; i < lineCount; ++i) {
        // Взимаме оригиналния текст и създаваме негова "подрязана" версия.
        std::string originalText = doc->getLineText(i);
        std::string trimmedText = trim_helper(originalText);

        // Променяме реда в документа само ако е имало промяна, за да е по-ефективно.
        if (originalText != trimmedText) {
            doc->setLineText(i, trimmedText);
        }
    }
}

// Тази имплементация е "груба", но ефективна: изтрива всичко и го създава наново
// от резервното копие, което направихме в execute().
void TrimCommand::undo() {
    // Първо, изтриваме напълно текущото съдържание на документа.
    size_t currentLineCount = doc->getLineCount();
    for (size_t i = 0; i < currentLineCount; ++i) {
        // Трием първия ред отново и отново, докато документът не остане празен.
        doc->removeLine(0);
    }

    // След това, възстановяваме документа от нашето резервно копие.
    for (size_t i = 0; i < originalLines.size(); ++i) {
        // Вмъкваме всеки ред от 'originalLines' обратно в (вече празния) документ.
        doc->insertLine(i, originalLines[i]);
    }
}

void TrimCommand::setDocument(TextDocument* newDoc) {
    this->doc = newDoc;
}

